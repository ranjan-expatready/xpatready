// B120 walk at 1440 px (P-352): Demo › Load the configured checkpoint, its rows, on to a combination, Reset to the six.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
const NM = "/home/user/xpatready/ai-workers/problem-1-pathway-setup-and-form-filling/prototype/studio/node_modules";
const { chromium } = await import(join(NM, "playwright", "index.mjs"));
const [port, out] = process.argv.slice(2);
const base = `http://localhost:${port}`, notes = [], note = (s) => { notes.push(s); console.log(s); };
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 });
await ctx.addInitScript(() => { try { localStorage.setItem("xr-actor", "user-A"); } catch {} });
const p = await ctx.newPage(); const errors = [];
p.on("pageerror", (e) => errors.push(String(e).slice(0, 200))); p.on("response", (r) => { if (r.status() >= 400) errors.push(`${r.status()} ${r.request().method()} ${new URL(r.url()).pathname} (after: ${notes.at(-1) ?? "start"})`); }); p.on("console", (m) => { if (m.type() === "error") errors.push(m.text().slice(0, 200)); });
await p.goto(base + "/"); await p.waitForLoadState("networkidle");
const demo = p.getByRole("button", { name: /^Demo/ });
await demo.click(); await p.getByRole("menuitem", { name: /Load the configured checkpoint/ }).click();
await p.getByRole("dialog", { name: /Load the configured checkpoint\?/ }).waitFor();
await p.screenshot({ path: join(out, "1-confirm-1440.png") });
const t0 = Date.now();
await p.getByRole("dialog").getByRole("button", { name: /^Load the configured checkpoint$/ }).click();
await p.getByRole("dialog", { name: /Configured checkpoint loaded/ }).waitFor({ timeout: 1_200_000 });
note(`loaded through the menu in ${((Date.now() - t0) / 1000).toFixed(0)} s`);
await p.screenshot({ path: join(out, "2-rows-1440.png") });
const rows = await p.$$eval("[data-conf-row]", (rs) => rs.map((r) => `${r.getAttribute("data-conf-row")}:${r.getAttribute("data-status")}`));
note(`rows on screen: ${rows.join(" ")}`);
const api = await (await fetch(base + "/api/demo/status", { headers: { "x-actor": "user-A" } })).json();
note(`status: loaded ${api.loaded}`);
await p.getByRole("button", { name: "Continue" }).click();
// The next step a person takes: a combination the checkpoint set up (its Visitor visa, released).
await p.getByText("Visitor visa", { exact: false }).first().click();
await p.waitForLoadState("networkidle"); await p.waitForTimeout(800);
note(`next step: ${await p.title()} at ${new URL(p.url()).pathname}`);
await p.screenshot({ path: join(out, "3-visitor-visa-1440.png") });
await demo.click(); await p.getByRole("menuitem", { name: /Reset to the six/ }).click();
await p.getByRole("dialog", { name: /Reset to the six\?/ }).waitFor();
await p.getByLabel("Type RESET to confirm").fill("RESET");
await p.getByLabel("Type RESET to confirm").press("Enter");
await p.getByRole("dialog", { name: /Reset to the six\?/ }).waitFor({ state: "detached", timeout: 600_000 });
await p.waitForLoadState("networkidle");
await p.screenshot({ path: join(out, "4-after-reset-to-six-1440.png") });
note(`Reset to the six: done`);
note(`page and console errors: ${errors.length ? errors.join(" | ") : "none"}`);
writeFileSync(join(out, "walk.txt"), notes.join("\n") + "\n");
await browser.close();
