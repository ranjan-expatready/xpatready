// Turns crawl JSON files + the planner's scores.json into one YAML file per screen.
// Usage: node gen-inventory.mjs <scores.json> <outdir> <crawl.json...>
import fs from "fs";
import path from "path";
const [, , scoresFile, outdir, ...crawls] = process.argv;
const scores = JSON.parse(fs.readFileSync(scoresFile, "utf8"));
fs.mkdirSync(outdir, { recursive: true });

const q = (s) => {
  s = String(s);
  // Plain only when clearly safe; everything else as a JSON string (a valid YAML double-quoted scalar).
  if (/^[A-Za-z][\w .()\/@+'-]*$/.test(s) && !/^(true|false|null|yes|no|on|off|y|n)$/i.test(s) && !/\s$/.test(s)) return s;
  return JSON.stringify(s);
};
function y(v, ind = 0) {
  const pad = "  ".repeat(ind);
  if (Array.isArray(v)) {
    if (!v.length) return " []";
    if (v.every((x) => typeof x !== "object" || x === null)) { const line = " [" + v.map(q).join(", ") + "]"; if (line.length < 110) return line; }
    return "\n" + v.map((x) => {
      if (x && typeof x === "object" && !Array.isArray(x)) { const ks = Object.keys(x); return pad + "- " + ks.map((k, i) => (i ? pad + "  " : "") + k + ":" + y(x[k], ind + 2)).join("\n"); }
      return pad + "-" + y(x, ind + 1);
    }).join("\n");
  }
  if (v && typeof v === "object") { const ks = Object.keys(v); if (!ks.length) return " {}"; return "\n" + ks.map((k) => pad + k + ":" + y(v[k], ind + 1)).join("\n"); }
  if (typeof v === "boolean" || typeof v === "number") return " " + v;
  if (v == null) return " null";
  return " " + q(v);
}

const all = crawls.flatMap((f) => JSON.parse(fs.readFileSync(f, "utf8")));
const byId = new Map();
for (const r of all) { if (!byId.has(r.id)) byId.set(r.id, []); byId.get(r.id).push(r); }
const index = [];
for (const [id, runs] of byId) {
  const wide = runs.find((r) => r.width >= 1000) ?? runs[0];
  const narrow = runs.find((r) => r.width < 600);
  const sc = scores.screens?.[id] ?? {};
  const doc = {
    screen: id,
    title: wide.label,
    route: wide.path.replace(/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/g, ":id"),
    persona: { "user-A": "Configuration author", "user-B": "Approver", "user-C": "Content reviewer", "user-O": "Case officer", "user-R": "Representative", "user-P": "Client A" }[wide.actor] ?? wide.actor,
    crawled: { date: scores.date, commit: scores.commit, data: sc.data ?? scores.data ?? "", load_ms: { 1440: wide.load_ms, 375: narrow?.load_ms ?? null } },
    purpose: sc.purpose ?? "",
    on_journey: sc.on_journey ?? false,
    pattern: sc.pattern ?? "",
    states: wide.states.map((s) => s.state),
    screenshots: runs.flatMap((r) => r.states.map((s) => `shots/${s.shot}`)),
    counts: {},
    axe: {},
    sections: [],
    scores: sc.scores ?? {},
    top_problems: sc.problems ?? [],
    findings: sc.findings ?? [],
  };
  for (const r of runs) for (const s of r.states) {
    const c = { ...s.counts }; delete c.type_sizes;
    doc.counts[`${s.state}@${r.width}`] = c;
    doc.axe[`${s.state}@${r.width}`] = s.axe.length ? s.axe.map((a) => `${a.id} (${a.impact}, ${a.nodes})`) : "0 violations";
  }
  for (const s of wide.states) doc.sections.push({ state: s.state, h1: s.h1.join(" | "), sections: s.sections.map((x) => ({ heading: x.heading, ...(x.fields ? { fields: x.fields } : {}), ...(x.actions ? { actions: x.actions.map((a) => [a.label, a.primary ? "PRIMARY" : "", a.disabled ? "disabled" : "", a.icon_only ? "icon-only" : "", a.tooltip ? `tip: ${a.tooltip}` : "", a.opens ? `opens ${a.opens}` : ""].filter(Boolean).join(" · ")) } : {}), ...(x.links ? { links: x.links.map((l) => `${l.label} → ${l.href.replace(/[0-9a-f]{8}-[0-9a-f-]{27}/g, ":id")}`) } : {}), ...(x.foldouts ? { foldouts: x.foldouts.map((f) => `${f.label}${f.arrow ? "" : " (NO ARROW)"}`) } : {}), ...(x.tabs ? { tabs: x.tabs.map((t) => t.label + (t.selected ? " (selected)" : "")) } : {}), ...(x.notes ? { notes: x.notes } : {}) })) });
  const header = `# UX inventory: ${id}. Generated by the crawl (design/ux-2026-11-11/tools/crawl.mjs) from the running app, then\n# scored by hand against 01-rubric.md. Ground truth for later rounds: re-crawl, diff, re-score (04 ux-audit).\n`;
  fs.writeFileSync(path.join(outdir, `${id}.yaml`), header + y(doc).replace(/^\n/, "") + "\n");
  index.push(id);
}
console.log(index.length, "screens:", index.join(" "));
