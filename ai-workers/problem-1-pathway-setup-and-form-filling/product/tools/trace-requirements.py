#!/usr/bin/env python3
"""trace-requirements.py: requirement traceability as data (P-595, row TR-1). Python standard library only (P-502).

The `Source:` convention for Release 1 backlog rows (rows whose id starts PF-, FO-, CS-, AUD-, BK- or SEC-; client
money is FO-7*). A shaped row (it has a Done when) carries, anywhere in its line, usually in the
"Source · waits on · decisions" column:

    Source: AG-2-84@3f9c1a2e, AG-2-5@0b1d77c4, P-559, official(IRCC IMM 5257 guide, p. 4, 2026-10-19), FEE-R01

  * a fine team requirement id with the first 8 hex of the sha256 of its text in the newest name-free copy
    `../domain/requirements-*/` (`--cite AG-2-84` prints it ready to paste);
  * a founder decision id `P-NNN` from DECISIONS.md;
  * an official source: `official(<what>, p. <page>, <YYYY-MM-DD>)`, or an id of `compliance-trace.md`, whose
    rows already carry the page, quote and date (AGENTS rule 4).
  Items are separated by commas outside parentheses; the field ends at ` · `, `|` or the line's end.

A team id's text is its definition in its own module file (`AG-02-...` holds AG-2-n): a card heading (`#### AG-2-31 —`)
up to the next heading of the same or a higher level; else a bold bullet (`- **SA-2-1** ...`) with its indented lines;
else a table row whose first cell starts with the id. The hash reads the text with spaces collapsed and the id itself
replaced by `<id>` on its first line, so a renumbered card keeps its hash and is found as renumbered.

  --cite ID...              print ID@hash for each id (for the row's Source)
  --brief ROW               print only the exact text of ROW's sources: the slice a brief carries
  --refresh OLD_DIR NEW_DIR added, removed, renumbered and changed ids between two snapshots, and the rows each hits
                            (run it after tools/sync-requirements.sh makes a new copy)
  --gaps                    unmapped rows (checklist §A Not shaped; shaped Release 1 rows with no Source), team ids no
                            row covers (by module), source problems, and possible conflicts with P-decisions (the Lead
                            checks them, then they go to the founder: AGENTS rule 2)
  --render                  write the Source and qa capability table into MVP-CHECKLIST.md §A between the generated
                            markers; never edit that block by hand; a second run changes nothing
  --check OLD_BACKLOG       CI (records PRs only): exit 1 when BACKLOG adds a shaped Release 1 row with no Source, or
                            with a source item that does not resolve
  --backlog/--checklist/--decisions/--capabilities/--trace FILE, --requirements DIR: other inputs (tests, fixtures)
Live AI off, reads files only, US$0. Tests: tools/test_trace_requirements.py.
"""
import argparse, contextlib, hashlib, io, pathlib, re, sys

TOOLS = pathlib.Path(__file__).resolve().parent
PRODUCT = TOOLS.parent
DOMAIN = PRODUCT.parent / "domain"

ID = r"(?:AG|SA)-\d{1,2}[A-Z]?-\d{1,3}[a-z]?"
ID_RE = re.compile(r"\b(" + ID + r")\b")
MODULE_FILE = re.compile(r"^(AG|SA)-(\d{2})([A-Z]?)-.+_v\d+(?:\.\d+)*_(\d{4}-\d{2}-\d{2})\.md$")
R1_ROW = re.compile(r"^(?:PF|FO|CS|AUD|BK|SEC)-[0-9][0-9A-Za-z.]*$")
P_ID = re.compile(r"^P-\d+$")
TEAM_ITEM = re.compile(r"^(" + ID + r")(?:@([0-9a-f]{8}))?$")
OFFICIAL = re.compile(r"^official\((.+)\)$")
PAGE = re.compile(r"\b(?:p\.|pp\.|page)\s*\d+", re.I)
DATE = re.compile(r"\b\d{4}-\d{2}-\d{2}\b")
PLACEHOLDER = {"", "-", "—", "tbd", "named only", "(named)"}
CONFLICT_WORDS = re.compile(r"\b(out of the first build|stays? out|instead of|overrid\w*|overrul\w*|departs? from|"
                            r"differs? from|dropped|drops?|rather than|withdrawn|replaces?|not built)\b", re.I)
BEGIN = "<!-- trace-requirements:begin (generated by tools/trace-requirements.py --render; never edit by hand) -->"
END = "<!-- trace-requirements:end -->"


def short_hash(text):
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:8]


def module_of(rid):
    return rid.rsplit("-", 1)[0]


# ---------------------------------------------------------------- requirements
class Req:
    def __init__(self, rid, path, line, kind, lines, group):
        self.id, self.path, self.line, self.kind, self.group = rid, path, line, kind, group
        self.text = "\n".join(lines).rstrip()
        first = lines[0]
        for g in group:
            first = re.sub(r"\b" + re.escape(g) + r"\b", "<id>", first)
        self.hash = short_hash(" ".join(" ".join([first] + lines[1:]).split()))


def _expand(prefix):
    """Ids named at the start of a definition, with ranges (AG-6-1 – AG-6-8) filled in."""
    ids = ID_RE.findall(prefix)
    for a, b in re.findall(r"(" + ID + r")\s*(?:–|-|to)\s*(" + ID + r")", prefix):
        ma, mb = re.match(r"(.+)-(\d+)$", a), re.match(r"(.+)-(\d+)$", b)
        if ma and mb and ma.group(1) == mb.group(1) and int(ma.group(2)) < int(mb.group(2)) <= int(ma.group(2)) + 50:
            ids += [f"{ma.group(1)}-{n}" for n in range(int(ma.group(2)) + 1, int(mb.group(2)))]
    out = []
    for i in ids:
        if i not in out:
            out.append(i)
    return out


def _lead(prefix):
    """The id list that opens a definition, before any note in brackets: 'AG-6-44 (with AG-6-5)' names AG-6-44."""
    return re.split(r"\s*\*?\(", prefix, maxsplit=1)[0]


def parse_module(path, module):
    lines = path.read_text(encoding="utf-8").split("\n")
    heads = [(i, len(m.group(1))) for i, l in enumerate(lines) for m in [re.match(r"^(#{1,6})\s", l)] if m]
    cands = {}  # id -> list of (rank, group size, line, Req)

    def add(group, i, kind, body):
        group = [g for g in group if module_of(g) == module]
        for g in group:
            rank = {"heading": 0, "bullet": 1, "table": 2}[kind]
            cands.setdefault(g, []).append((rank, len(group), i, Req(g, path, i + 1, kind, body, group)))

    for n, l in enumerate(lines):
        m = re.match(r"^(#{2,6})\s+(?:~~)?\**\s*(" + ID + r".*)$", l)
        if m:
            level, rest = len(m.group(1)), m.group(2)
            prefix = _lead(re.split(r"\s+—\s+", rest, maxsplit=1)[0][:160])
            end = next((i for i, lv in heads if i > n and lv <= level), len(lines))
            add(_expand(prefix), n, "heading", lines[n:end])
            continue
        m = re.match(r"^(\s*)[-*]\s+(?:~~)?\*\*(" + ID + r".{0,200}?)\*\*", l)
        if m:
            indent, end = len(m.group(1)), n + 1
            while end < len(lines) and lines[end].strip() and len(lines[end]) - len(lines[end].lstrip()) > indent:
                end += 1
            add(_expand(_lead(m.group(2))), n, "bullet", lines[n:end])
            continue
        m = re.match(r"^\|\s*(?:~~)?\**\s*(" + ID + r")", l)
        if m:
            first = l.split("|")[1]
            add(_expand(re.split(r"[(:]", first)[0]), n, "table", [l])
    return {rid: sorted(c, key=lambda x: x[:3])[0][3] for rid, c in cands.items()}


def load_snapshot(d):
    """id -> Req for one requirements copy; the newest version of each module file."""
    d = pathlib.Path(d)
    files = {}
    for p in sorted(d.rglob("*.md")):
        m = MODULE_FILE.match(p.name)
        if m:
            mod = f"{m.group(1)}-{int(m.group(2))}{m.group(3)}"
            if mod not in files or (m.group(4), p.name) > (files[mod][0], files[mod][1].name):
                files[mod] = (m.group(4), p)
    reqs = {}
    for mod, (_, p) in sorted(files.items()):
        reqs.update(parse_module(p, mod))
    return reqs, {mod: p for mod, (_, p) in files.items()}


def newest_requirements():
    dirs = sorted(DOMAIN.glob("requirements-*"))
    if not dirs:
        sys.exit(f"no requirements copy under {DOMAIN} (tools/sync-requirements.sh makes one)")
    return dirs[-1]


# ---------------------------------------------------------------- backlog rows and sources
def split_cells(line):
    """Cells of a markdown table line; a | inside `code` or escaped as \\| does not split."""
    cells, cur, code, i = [], "", False, 0
    while i < len(line):
        c = line[i]
        if c == "\\" and i + 1 < len(line) and line[i + 1] == "|":
            cur += "|"; i += 2; continue
        if c == "`":
            code = not code
        if c == "|" and not code:
            cells.append(cur.strip()); cur = ""
        else:
            cur += c
        i += 1
    cells.append(cur.strip())
    return cells[1:-1] if line.strip().startswith("|") else cells


def split_items(text):
    items, cur, depth = [], "", 0
    for c in text:
        depth += (c == "(") - (c == ")")
        if c in ",;" and depth == 0:
            items.append(cur); cur = ""
        else:
            cur += c
    items.append(cur)
    return [i.strip().strip("*`").strip() for i in items if i.strip().strip("*`").strip()]


def parse_source(line):
    """None when the row has no Source field; else the list of items."""
    for cell in (split_cells(line) if line.lstrip().startswith("|") else [line]):
        m = re.search(r"\bSource:\**\s*(.*)", cell)
        if m:
            return split_items(re.split(r"\s·\s|\n", m.group(1))[0])
    return None


class Row:
    def __init__(self, rid, label, line, lineno, shaped):
        self.id, self.label, self.line, self.lineno, self.shaped = rid, label, line, lineno, shaped
        self.source = parse_source(line)


def parse_backlog(text):
    """Release 1 rows in table order (an amendment row 'FO-2 (rev 15.1 amendment)' keeps its parent's id)."""
    rows, header, last = [], None, None
    lines = text.split("\n")
    for n, l in enumerate(lines):
        if not l.startswith("|"):
            header = None; continue
        if re.match(r"^\|\s*:?-{3,}", l):
            header = last = [h.lower() for h in split_cells(lines[n - 1])] if n else None; continue
        cells = split_cells(l)
        if header is None and (n == 0 or not lines[n - 1].startswith("|")):
            header = last  # rows that continue a table after a note, with no header of their own
        if not cells or header is None:
            continue
        first = re.sub(r"[*~]", "", cells[0]).strip()
        rid = first.split(" ")[0]
        if not R1_ROW.match(rid):
            continue
        dw = next((k for k, h in enumerate(header) if "done when" in h), None)
        shaped = dw is not None and dw < len(cells) and cells[dw].strip().lower() not in PLACEHOLDER
        rows.append(Row(rid, first, l, n + 1, shaped))
    return rows


def decisions(text):
    """P-id -> (row text, struck or amended note or '')."""
    out = {}
    for l in text.split("\n"):
        m = re.match(r"^\|\s*(?:~~)?(P-\d+)(?:~~)?\s*\|", l)
        if m:
            cells = split_cells(l)
            body = cells[-1] if cells else ""
            note = ""
            if body.startswith("~~") or l.lstrip("| ").startswith("~~"):
                note = "struck"
            am = re.search(r"\((?:amended|superseded|replaced) by (P-\d+)", body)
            if am:
                note = f"amended by {am.group(1)}"
            out.setdefault(m.group(1), (l, note))
    return out


def trace_ids(text):
    return set(re.findall(r"^\|\s*([A-Z]{2,6}-R?\d+[a-z]?)\s*\|", text, re.M))


class Ctx:
    def __init__(self, a):
        self.a = a
        self.req_dir = pathlib.Path(a.requirements) if a.requirements else newest_requirements()
        self._reqs = None

    def reqs(self):
        if self._reqs is None:
            self._reqs = load_snapshot(self.req_dir)
        return self._reqs

    def read(self, name):
        p = pathlib.Path(getattr(self.a, name))
        return p.read_text(encoding="utf-8") if p.exists() else ""


def check_item(item, ctx, decs, tids):
    """('team'|'decision'|'official', key, problem or None)."""
    m = TEAM_ITEM.match(item)
    if m:
        reqs = ctx.reqs()[0]
        rid, h = m.group(1), m.group(2)
        if rid not in reqs:
            return "team", rid, f"{rid} is not defined in {ctx.req_dir.name}"
        if not h:
            return "team", rid, f"{rid} has no @hash (now @{reqs[rid].hash})"
        if h != reqs[rid].hash:
            return "team", rid, f"{rid}@{h} is stale: its text changed, now @{reqs[rid].hash}"
        return "team", rid, None
    if P_ID.match(item):
        if decs and item not in decs:
            return "decision", item, f"{item} is not in DECISIONS.md"
        note = decs.get(item, ("", ""))[1]
        return "decision", item, (f"{item} is {note}" if note else None)
    m = OFFICIAL.match(item)
    if m:
        ok = PAGE.search(m.group(1)) and DATE.search(m.group(1))
        return "official", item, None if ok else f"{item} needs a page and a date (YYYY-MM-DD)"
    if item in tids:
        return "official", item, None
    return "unknown", item, f"'{item}' is not a team id@hash, a P-decision, official(...) or a compliance-trace id"


# ---------------------------------------------------------------- commands
def cmd_cite(ctx, ids):
    reqs = ctx.reqs()[0]
    bad = [i for i in ids if i not in reqs]
    print(", ".join(f"{i}@{reqs[i].hash}" for i in ids if i in reqs))
    for i in bad:
        print(f"not defined in {ctx.req_dir.name}: {i}", file=sys.stderr)
    return 1 if bad else 0


def cmd_brief(ctx, row_id):
    rows = [r for r in parse_backlog(ctx.read("backlog")) if r.id == row_id]
    if not rows:
        print(f"no Release 1 row {row_id} in {ctx.a.backlog}", file=sys.stderr); return 2
    items = []
    for r in rows:
        for i in r.source or []:
            if i not in items:
                items.append(i)
    if not items:
        print(f"{row_id} has no Source: line yet (unmapped); shape it first", file=sys.stderr); return 1
    reqs, files = ctx.reqs()
    decs, tids = decisions(ctx.read("decisions")), trace_ids(ctx.read("trace"))
    out = io.StringIO()
    with contextlib.redirect_stdout(out):
        _brief_body(row_id, items, ctx, reqs, decs, tids)
    print(out.getvalue(), end="")
    team = [m.group(1) for m in map(TEAM_ITEM.match, items) if m and m.group(1) in reqs]
    mods = sorted({module_of(i) for i in team})
    size = sum(files[m].stat().st_size for m in mods)
    if size:
        n = len(out.getvalue().encode("utf-8"))
        print(f"slice: {n} bytes = {100 * n / size:.1f}% of {', '.join(mods)} ({size} bytes)", file=sys.stderr)
    return 0


def _brief_body(row_id, items, ctx, reqs, decs, tids):
    print(f"# {row_id}: requirement text ({ctx.req_dir.name}; cite these ids, read only this text)\n")
    print("Source: " + ", ".join(items) + "\n")
    for i in items:
        kind, key, problem = check_item(i, ctx, decs, tids)
        if problem:
            print(f"> WARNING: {problem}\n")
        if kind == "team" and key in reqs:
            q = reqs[key]
            print(f"## {key} @{q.hash} ({q.path.name}:{q.line})\n\n{q.text}\n")
        elif kind == "decision" and key in decs:
            print(f"## {key} (DECISIONS.md)\n\n{decs[key][0]}\n")
        elif kind == "official":
            line = next((l for l in ctx.read("trace").split("\n") if l.startswith(f"| {key} |")), i)
            print(f"## {key}\n\n{line}\n")


def diff_snapshots(old, new):
    added = sorted(set(new) - set(old), key=_idkey)
    removed = sorted(set(old) - set(new), key=_idkey)
    changed = [i for i in sorted(set(old) & set(new), key=_idkey) if old[i].hash != new[i].hash]
    # Renumbered: the old text of a removed or changed id is now, unchanged, under one other id (a card inserted
    # ahead shifts the ids after it). Only hashes held by one id on each side count.
    old_n, new_at = {}, {}
    for i, q in old.items():
        old_n[q.hash] = old_n.get(q.hash, 0) + 1
    for i, q in new.items():
        new_at.setdefault(q.hash, []).append(i)
    renumbered = [(o, new_at[old[o].hash][0]) for o in removed + changed
                  if old_n[old[o].hash] == 1 and len(new_at.get(old[o].hash, [])) == 1 and new_at[old[o].hash][0] != o]
    renumbered.sort(key=lambda x: _idkey(x[0]))
    gone = {o for o, _ in renumbered} | {n for _, n in renumbered}
    return ([i for i in added if i not in gone], [i for i in removed if i not in gone], renumbered, changed)


def _idkey(i):
    p = re.match(r"(AG|SA)-(\d+)([A-Z]?)-(\d+)([a-z]?)", i)
    return (p.group(1), int(p.group(2)), p.group(3), int(p.group(4)), p.group(5)) if p else (i,)


def rows_citing(rows):
    hits = {}
    for r in rows:
        for i in r.source or []:
            m = TEAM_ITEM.match(i)
            if m and r.id not in hits.setdefault(m.group(1), []):
                hits[m.group(1)].append(r.id)
    return hits


def by_module(ids):
    out = {}
    for i in ids:
        out.setdefault(module_of(i), []).append(i)
    return out


def cmd_refresh(ctx, old_dir, new_dir):
    old, new = load_snapshot(old_dir)[0], load_snapshot(new_dir)[0]
    added, removed, renum, changed = diff_snapshots(old, new)
    hits = rows_citing(parse_backlog(ctx.read("backlog")))
    print(f"# Requirements refresh: {pathlib.Path(old_dir).name} → {pathlib.Path(new_dir).name}\n")
    print(f"ids: {len(old)} → {len(new)} · added {len(added)} · removed {len(removed)} · "
          f"renumbered {len(renum)} · changed {len(changed)}\n")
    hit_lines = []
    for title, ids in (("Changed (same id, new text)", changed), ("Removed", removed), ("Added", added)):
        print(f"## {title}: {len(ids)}\n")
        for mod, mids in by_module(ids).items():
            print(f"* {mod} ({len(mids)}): " + ", ".join(
                f"{i} {old[i].hash}→{new[i].hash}" if title.startswith("Changed") else i for i in mids))
        print()
        hit_lines += [f"* {i} ({title.split(' ')[0].lower()}): {', '.join(hits[i])}" for i in ids if i in hits]
    print(f"## Renumbered (same text, new id): {len(renum)}\n")
    for o, n in renum:
        print(f"* {o} → {n} @{new[n].hash}")
        if o in hits:
            hit_lines.append(f"* {o} (renumbered to {n}): {', '.join(hits[o])}")
    print("\n## Backlog rows hit\n")
    print("\n".join(hit_lines) if hit_lines else "none: no row's Source cites a changed, removed or renumbered id")
    return 0


def checklist_rows(text):
    """§A map rows: (map, capability, backlog cell, status)."""
    out, in_a, in_gen = [], False, False
    for l in text.split("\n"):
        if l.startswith("## "):
            in_a = l.startswith("## A.")
        if l.startswith(BEGIN[:30]):
            in_gen = True
        if l.startswith(END):
            in_gen = False; continue
        if not in_a or in_gen or not re.match(r"^\|\s*\d+\s*\|", l):
            continue
        c = split_cells(l)
        if len(c) >= 5:
            out.append((c[0], c[1], c[3], c[4]))
    return out


def cmd_gaps(ctx):
    rows = parse_backlog(ctx.read("backlog"))
    decs, tids = decisions(ctx.read("decisions")), trace_ids(ctx.read("trace"))
    reqs = ctx.reqs()[0]
    not_shaped = [r for r in checklist_rows(ctx.read("checklist")) if r[3].lower().startswith("not shaped")]
    no_source = []
    for r in rows:
        if r.shaped and r.source is None and not any(x.id == r.id and x.source for x in rows) \
                and r.id not in no_source:
            no_source.append(r.id)
    print(f"# Requirement gaps ({ctx.req_dir.name})\n")
    if not pathlib.Path(ctx.a.checklist).exists():
        print(f"(no checklist at {ctx.a.checklist}: §A rows not read)\n")
    print(f"## Unmapped: {len(not_shaped)} checklist §A rows not shaped, {len(no_source)} shaped Release 1 rows "
          "with no Source\n")
    for m, cap, cell, st in not_shaped:
        print(f"* map {m}: {cap} (rows: {cell}; {st})")
    print("\n" + (("* rows with no Source: " + ", ".join(no_source)) if no_source else "* every shaped row has a Source"))
    covered = set(rows_citing(rows))
    uncovered = [i for i in sorted(reqs, key=_idkey) if i not in covered]
    print(f"\n## Team requirement ids no row covers: {len(uncovered)} of {len(reqs)}\n")
    for mod, mids in by_module(uncovered).items():
        print(f"* {mod} ({len(mids)}): {', '.join(mids)}")
    problems, conflicts = [], []
    against = {}
    for p, (line, note) in decs.items():
        if note:
            continue
        for s in re.split(r"(?<=[.;])\s+", line):
            if CONFLICT_WORDS.search(s):
                for i in ID_RE.findall(s):
                    against.setdefault(i, []).append((p, " ".join(s.split())[:200]))
    for r in rows:
        items = r.source or []
        for i in items:
            kind, key, problem = check_item(i, ctx, decs, tids)
            if problem:
                (conflicts if kind == "decision" and decs.get(key, ("", ""))[1] else problems).append(f"{r.id}: {problem}")
            if kind == "team":
                for p, s in against.get(key, []):
                    if p not in items:
                        conflicts.append(f"{r.id} cites {key}; {p} says: \"{s}\"")
    print(f"\n## Source problems: {len(problems)}\n")
    print("\n".join(f"* {x}" for x in problems) or "none")
    print(f"\n## Possible conflicts with P-decisions (the Lead checks; then the founder, AGENTS rule 2): {len(conflicts)}\n")
    print("\n".join(f"* {x}" for x in conflicts) or "none")
    return 0


def render_block(ctx):
    rows = parse_backlog(ctx.read("backlog"))
    srcs = {}
    for r in rows:
        for i in r.source or []:
            if i not in srcs.setdefault(r.id, []):
                srcs[r.id].append(i)
    known = {r.id for r in rows}
    caps, r1 = {}, {}  # C-rows by id; R1 rows (qa's Release 1 list) by the map row in their second cell
    for l in ctx.read("capabilities").split("\n"):
        c = split_cells(l) if l.startswith("| C") or l.startswith("| R1.") else []
        if len(c) >= 5 and re.match(r"^C\d+\.\d+$", c[0]):
            caps[c[0]] = c[4]
        elif len(c) >= 4 and re.match(r"^R1\.\d+$", c[0]) and re.match(r"^\d+ ", c[1]):
            r1.setdefault(c[1].split(" ")[0], []).append(f"{c[0]} {c[3]}")
    out = [BEGIN, f"### A. Sources and qa capabilities ({ctx.req_dir.name})", "",
           "| Map | Capability | BACKLOG rows | Source | qa capability |", "|---|---|---|---|---|"]
    for m, cap, cell, st in checklist_rows(ctx.read("checklist")):
        ids = []
        for t in re.findall(r"\b((?:PF|FO|CS|AUD|BK|SEC)-[0-9][0-9A-Za-z]*|C\d+\.\d+)\b", cell):
            if t not in ids:
                ids.append(t)
        rids = [i for i in ids if not i.startswith("C")]
        src = []
        for i in rids:
            src += [s for s in srcs.get(i, []) if s not in src]
        qa = r1.get(m, []) + [f"{c} {caps[c]}" for c in ids if c.startswith("C") and c in caps]
        shown = ", ".join(i if i in known or i.startswith("C") else f"{i} (no row)" for i in ids) or "none"
        out.append(f"| {m} | {cap} | {shown} | {', '.join(src) or 'unmapped'} | {', '.join(qa) or 'none yet'} |")
    return out + ["", END]


def cmd_render(ctx):
    path = pathlib.Path(ctx.a.checklist)
    if not path.exists():
        print(f"no checklist at {path}", file=sys.stderr); return 2
    text = path.read_text(encoding="utf-8")
    block = "\n".join(render_block(ctx))
    if BEGIN in text and END in text:
        new = text[:text.index(BEGIN)] + block + text[text.index(END) + len(END):]
    else:
        lines = text.split("\n")
        a = next((k for k, l in enumerate(lines) if l.startswith("## A.")), None)
        if a is None:
            print(f"no '## A.' section in {path}", file=sys.stderr); return 2
        at = next((k for k, l in enumerate(lines) if k > a and (l.startswith("### Flags") or l.startswith("## "))),
                  len(lines))
        new = "\n".join(lines[:at] + [block, ""] + lines[at:])
    if new != text:
        path.write_text(new, encoding="utf-8")
    print(f"{'updated' if new != text else 'unchanged'}: {path}")
    return 0


def cmd_check(ctx, old_backlog):
    old_text = pathlib.Path(old_backlog).read_text(encoding="utf-8") if pathlib.Path(old_backlog).exists() else ""
    old_shaped = {r.id for r in parse_backlog(old_text) if r.shaped}
    old_lines = set(old_text.split("\n"))
    decs, tids = decisions(ctx.read("decisions")), trace_ids(ctx.read("trace"))
    rows = parse_backlog(ctx.read("backlog"))
    sourced = {r.id for r in rows if r.source}
    bad = []
    for r in rows:  # a row shaped by this change: new, or unshaped before (an edit to a shaped row is not checked)
        if r.id in old_shaped or r.line in old_lines or not r.shaped:
            continue
        if r.source is None and r.id in sourced:
            continue  # an amendment row; its parent row carries the Source
        if r.source is None:
            bad.append(f"{r.label} (line {r.lineno}): a new shaped Release 1 row needs a Source: line")
            continue
        for i in r.source:
            problem = check_item(i, ctx, decs, tids)[2]
            if problem and "amended" not in problem and "struck" not in problem:
                bad.append(f"{r.label} (line {r.lineno}): {problem}")
    for b in bad:
        print(f"FAIL  {b}")
    print("FAIL: see tools/trace-requirements.py's header for the Source convention" if bad
          else "PASS  every new shaped Release 1 row carries a Source that resolves")
    return 1 if bad else 0


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--cite", nargs="+", metavar="ID")
    g.add_argument("--brief", metavar="ROW")
    g.add_argument("--refresh", nargs=2, metavar=("OLD_DIR", "NEW_DIR"))
    g.add_argument("--gaps", action="store_true")
    g.add_argument("--render", action="store_true")
    g.add_argument("--check", metavar="OLD_BACKLOG")
    ap.add_argument("--backlog", default=str(PRODUCT / "BACKLOG.md"))
    ap.add_argument("--checklist", default=str(PRODUCT / "MVP-CHECKLIST.md"))
    ap.add_argument("--decisions", default=str(PRODUCT / "DECISIONS.md"))
    ap.add_argument("--capabilities", default=str(PRODUCT / "qa" / "CAPABILITIES.md"))
    ap.add_argument("--trace", default=str(PRODUCT / "compliance-trace.md"))
    ap.add_argument("--requirements", help="requirements copy (default: the newest ../domain/requirements-*)")
    a = ap.parse_args(argv)
    if a.refresh and not a.requirements:
        a.requirements = a.refresh[1]
    ctx = Ctx(a)
    if a.cite:
        return cmd_cite(ctx, a.cite)
    if a.brief:
        return cmd_brief(ctx, a.brief)
    if a.refresh:
        return cmd_refresh(ctx, *a.refresh)
    if a.gaps:
        return cmd_gaps(ctx)
    if a.render:
        return cmd_render(ctx)
    return cmd_check(ctx, a.check)


if __name__ == "__main__":
    sys.exit(main())
