def reconstruct(f, edits):
    """B0 source + recorded content edits + recorded plumbing edits; must equal the working file byte for byte."""
    src = open(os.path.join(B0S, f)).read()
    for old, new in [(e["old"], e["new"]) for e in edits if e["file"] == f] + PLUMBING_EDITS.get(f, []):
        if src.count(old) != 1:
            return None, f"recorded edit does not match B0 exactly once: {old[:70]!r}"
        src = src.replace(old, new)
    return src, None


# Builder plumbing changed by hand when the working edition was created (write guard and working paths; no page content).
# Evidence that it does not change the page: built before apply_w1.py, the working builder reproduced 124df0a2…8445.
PLUMBING = {"build_one_pager.py": ["Build the Solution 1 one-pager, draft 2, from s3_data.py", "solution-1-one-pager.html", "w",
                                   "18 October 2026 · generated by `tools/s3/build_one_pager.py`", "one-pager-detail-panels-preservation-2026-10-18.md",
                                   "ledger module missing"]}


def sha(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()


def main():
    errs = []
    edits = json.load(open(os.path.join(HERE, "w1_edits.json")))
    # 1. frozen originals unchanged against B0's manifest
    man = {l.split("  ", 1)[1].strip(): l.split("  ", 1)[0] for l in open(os.path.join(B0, "manifest.sha256")) if "  " in l}
    frozen = ["ai-workers/problem-1-pathway-setup-and-form-filling/solution-1-one-pager.html"] + [f"ai-workers/tools/s3/{f}" for f in FILES + ["s3_terms.py", "s3_ledger.py"]]
    for rel in frozen:
        live = os.path.join(os.path.dirname(AW), rel)
        if sha(live) != man[rel]:
            errs.append(f"frozen file changed: {rel}")
    # 2. every edit applied exactly as recorded
    for e in edits:
        if e["new"] not in open(os.path.join(HERE, e["file"])).read():
            errs.append(f"recorded edit not present in {e['file']}: {e['new'][:70]}")
    # 3. each working file equals B0 + recorded edits, exactly (catches any unrecorded change, even inside an edited string)
    for f in FILES + ["s3_terms.py"]:
        exp, err = reconstruct(f, edits)
        if err:
            errs.append(f"{f}: {err}"); continue
        act = open(os.path.join(HERE, f)).read()
        if exp != act:
            k = next(i for i, (x, y) in enumerate(zip(exp.splitlines(), act.splitlines() + [""])) if x != y)
            errs.append(f"{f}: differs from B0 + recorded edits at line {k + 1}: no recorded edit explains {act.splitlines()[k][:90]!r}")
    # 4. removed strings, for the record: each is covered by an edit
    rows, new_count = [], 0
    for f in FILES:
        b0src = open(os.path.join(B0S, f)).read()
        espans = []
        for e in edits:
            if e["file"] == f:
                i = b0src.find(e["old"]); espans.append((i, i + len(e["old"]), e))
        old, now = strings(os.path.join(B0S, f), spans=True), strings(os.path.join(HERE, f))
        nowset = set(now)
        for s, a, b in old:
            if s in nowset:
                continue
            cover = [e for i, j, e in espans if i >= 0 and i < b and j > a]
            if not cover and any(s.startswith(p) for p in PLUMBING.get(f, [])):
                rows.append((f, s, "Working-edition plumbing (write guard and working paths; page unchanged, W0 = 124df0a2)")); continue
            if not cover:
                errs.append(f"{f}: B0 string changed with no recorded edit: {s[:90]!r}")
                continue
            rows.append((f, s, cover[0]["reason"]))
        new_count += len(set(now) - set(old))
    c = Counter(r for *_, r in rows)
    L = ["# Working edition W1: content ledger against B0 (accepted draft 4.3)", "",
         "Generated by `tools/s3-working/working_ledger.py`. Source of the edits: `tools/s3-working/apply_w1.py` (exact replacements, each matched once) and its record `w1_edits.json`.", "",
         f"**{len(rows)} B0 strings no longer appear word for word; every one is covered by a recorded edit. Unexplained changes: {len([e for e in errs if 'no recorded edit' in e])}. Removed without replacement: 0** (each edit replaces, none deletes). {new_count} strings are new or reworded in W1.", "",
         "By reason: " + "; ".join(f"{k} {v}" for k, v in sorted(c.items())), "",
         f"Frozen originals checked against the B0 manifest: {len(frozen)} files, {'all unchanged' if not any('frozen' in e for e in errs) else 'CHANGED'}.", "",
         "| File | B0 string (before) | Reason |", "|---|---|---|"]
    L += [f"| {f} | {s.replace('|', '/').replace(chr(10), ' ')[:400]} | {r} |" for f, s, r in rows]
    L += ["", "## Edits as recorded", "", "| # | File | Reason | New text (start) |", "|---|---|---|---|"]
    L += [f"| {i} | {e['file']} | {e['reason']} | {e['new'].replace('|', '/').replace(chr(10), ' ')[:220]} |" for i, e in enumerate(edits, 1)]
    guarded_write(os.path.join(AW, "checks", "working-edition", "w1-content-ledger.md"), "\n".join(L) + "\n")
    if errs:
        print("LEDGER FAILED:"); [print("  - " + e) for e in errs]; sys.exit(1)
    print(f"ledger: {len(rows)} changed B0 strings, all covered by {len(edits)} recorded edits; 0 unexplained; frozen originals unchanged")


if __name__ == "__main__":
    main()
